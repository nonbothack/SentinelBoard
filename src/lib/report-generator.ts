import type { IncidentActivity } from '@/types/database'
import type { AttachedEvent, AttachedIOC } from '@/lib/incidents'
import type { Incident } from '@/types/database'

export interface IncidentReportInput {
  incident: Incident
  iocs: Array<AttachedIOC & { enrichmentSummary?: string[] }>
  events: AttachedEvent[]
  timeline: IncidentActivity[]
  generatedAt?: Date
}

function cell(value: string | null | undefined) {
  return (value ?? '—').replaceAll('|', '\\|').replaceAll('\r\n', '<br>').replaceAll('\n', '<br>').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
}

function activityDescription(entry: IncidentActivity) {
  const details = entry.details && typeof entry.details === 'object' && !Array.isArray(entry.details) ? entry.details as Record<string, unknown> : {}
  switch (entry.action) {
    case 'incident_created': return `Created incident “${String(details.title ?? 'incident')}”`
    case 'incident_updated': return `Updated incident details${Array.isArray(details.changed_fields) ? ` (${details.changed_fields.join(', ')})` : ''}`
    case 'status_changed': return `Changed status from ${String(details.from ?? 'unknown')} to ${String(details.to ?? 'unknown')}`
    case 'ioc_attached': return `Attached IOC ${String(details.value ?? '')}`
    case 'event_attached': return `Attached event “${String(details.title ?? 'event')}”`
    default: return `Recorded activity: ${entry.action.replaceAll('_', ' ')}`
  }
}

export function generateIncidentReport({ incident, iocs, events, timeline, generatedAt = new Date() }: IncidentReportInput) {
  const iocRows = iocs.map(({ iocs: ioc, enrichmentSummary }) => `| ${cell(ioc?.type ?? 'IOC')} | ${cell(ioc?.value ?? 'Unavailable IOC')} | ${cell(ioc?.severity ?? 'Not enriched')} | ${cell(enrichmentSummary?.join('; ') || 'No enrichment summary available')} |`)
  const eventRows = [...events]
    .sort((left, right) => Date.parse(left.events?.event_time ?? '') - Date.parse(right.events?.event_time ?? ''))
    .map(({ events: event }) => `| ${cell(event?.event_time ?? '—')} | ${cell(event?.severity ?? '—')} | ${cell(event?.title ?? 'Unavailable event')} | ${cell(event?.source?.replaceAll('_', ' ') ?? '—')} |`)
  const activityRows = [...timeline]
    .sort((left, right) => Date.parse(left.created_at) - Date.parse(right.created_at))
    .map((entry) => `- [${entry.created_at}] ${cell(activityDescription(entry))}`)

  return [
    `# Incident Report: ${cell(incident.title)}`,
    '',
    `**ID**: \`${incident.id}\``,
    `**Severity**: ${incident.severity}`,
    `**Status**: ${incident.status}`,
    `**Created**: ${incident.created_at}`,
    `**Last Updated**: ${incident.updated_at}`,
    '',
    '## Description',
    '',
    cell(incident.description || 'No description provided.'),
    '',
    '## Associated Indicators of Compromise',
    '',
    '| Type | Value | Severity | Enrichment Summary |',
    '| :--- | :--- | :--- | :--- |',
    ...(iocRows.length ? iocRows : ['| — | No IOCs attached | — | — |']),
    '',
    '## Associated Events',
    '',
    '| Time | Severity | Title | Source |',
    '| :--- | :--- | :--- | :--- |',
    ...(eventRows.length ? eventRows : ['| — | — | No events attached | — |']),
    '',
    '## Investigation Timeline',
    '',
    ...(activityRows.length ? activityRows : ['- No activity recorded.']),
    '',
    '---',
    `*Report generated by SentinelBoard on ${generatedAt.toISOString()}*`,
    '',
  ].join('\n')
}

export function downloadIncidentReport(markdown: string, incidentId: string) {
  const blob = new Blob([markdown], { type: 'text/markdown;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = `incident-report-${incidentId}.md`
  anchor.click()
  URL.revokeObjectURL(url)
}
